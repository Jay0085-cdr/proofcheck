"""
copy_detector.py
Checks if a candidate's repo is mostly a copy of someone else's public repo.

The idea: git gives every file a "blob SHA", a fingerprint made from the file's
exact contents. Two files with the same SHA are byte-for-byte identical, even if
they live in different repos. So we can compare two repos just by comparing the
SHA lists from the Git Trees API, without downloading any code.
"""

import requests

from github_checker import API, SKIP_FOLDERS, RateLimitError, get_json, get_tree
from matcher import short_name

# Files that look the same in thousands of unrelated projects.
# Matching them proves nothing, so we never count them. (All lowercase.)
IGNORED_FILES = {
    # Licence, git and docs
    "license", "license.md", "license.txt", ".gitignore", ".gitattributes",
    "readme.md", "readme.txt", "readme",
    # Lock files (generated by npm / yarn / pnpm)
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml",
    # Vite and Create React App starter files
    "vite.config.js", "vite.config.ts", "eslint.config.js", "index.css", "app.css",
    "app.test.js", "setuptests.js", "reportwebvitals.js",
    # Default logos and icons
    "favicon.ico", "favicon.svg", "logo.svg", "logo192.png", "logo512.png",
    "vite.svg", "react.svg",
    # Python empty package marker
    "__init__.py",
}

# Generated or downloaded folders (node_modules, dist, build, venv, ...)
IGNORED_FOLDERS = SKIP_FOLDERS | {".github", ".idea", ".vscode"}

# Only files with these endings count as "source code"
SOURCE_EXTENSIONS = (
    ".py", ".js", ".jsx", ".ts", ".tsx", ".java", ".kt", ".go", ".rb", ".php",
    ".c", ".cpp", ".h", ".cs", ".rs", ".swift", ".dart", ".vue", ".html",
    ".css", ".scss", ".sql",
)

MAX_SOURCES = 5        # compare with at most 5 other repos
MAX_SEARCHES = 10      # GitHub search allows only ~10-30 searches a minute
MIN_IDENTICAL = 5      # need at least 5 identical files...
MIN_SHARE = 0.5        # ...and at least 50% of the candidate's source files

# How many searches we did in this run (reset by pipeline.py for each check)
search_count = 0


def is_source_file(item):
    """True for a real, non-empty code file that isn't boilerplate."""
    parts = item["path"].lower().split("/")
    name = parts[-1]
    return (
        item["type"] == "blob"
        and item.get("size", 0) > 0
        and name not in IGNORED_FILES
        and not any(folder in IGNORED_FOLDERS for folder in parts[:-1])
        and name.endswith(SOURCE_EXTENSIONS)
    )


def source_shas(full_name, branch):
    """The blob SHAs of the repo's source files."""
    return [item["sha"] for item in get_tree(full_name, branch) if is_source_file(item)]


def search_repos(query):
    """GitHub repo search, most stars first. Returns [] if search fails."""
    global search_count
    if search_count >= MAX_SEARCHES:
        return []
    search_count += 1
    try:
        data = get_json(
            f"{API}/search/repositories",
            params={"q": query, "sort": "stars", "order": "desc", "per_page": 10},
        )
    except (RateLimitError, requests.RequestException) as error:
        print(f"Search skipped: {error}")
        return []
    return (data or {}).get("items", [])


def find_sources(repo, project, username):
    """Up to 5 popular repos this one might be copied from."""
    sources = []
    if repo["parent"]:
        sources.append(repo["parent"])

    # Search 1: the repo name, e.g. "ghost-kitchen-payment" -> "ghost kitchen payment"
    # Search 2: the project's name from the resume plus its main tech
    name_words = repo["name"].replace("-", " ").replace("_", " ")
    queries = [f"{name_words} in:name"]
    if project.get("tech"):
        queries.append(f"{short_name(project['name'])} {project['tech'][0]}")

    for query in queries:
        for item in search_repos(query):
            if len(sources) >= MAX_SOURCES:
                return sources
            already_added = any(s["full_name"] == item["full_name"] for s in sources)
            is_own_repo = item["owner"]["login"].lower() == username.lower()
            if not already_added and not is_own_repo:
                sources.append({
                    "full_name": item["full_name"],
                    "default_branch": item["default_branch"],
                    "stars": item["stargazers_count"],
                })
    return sources


def find_copy(repo, project, username):
    """
    Returns {"source", "stars", "identical", "total"} if 50%+ of the repo's
    source files are identical to another repo's files, otherwise None.
    """
    mine = source_shas(repo["full_name"], repo["default_branch"])
    if len(mine) < MIN_IDENTICAL:
        return None  # too few files to judge

    best = None
    for source in find_sources(repo, project, username):
        try:
            # A set makes "is this SHA in there?" fast. Use ALL their files,
            # so a file that was moved or renamed still matches.
            theirs = {item["sha"] for item in get_tree(source["full_name"], source["default_branch"])}
        except (RateLimitError, requests.RequestException) as error:
            print(f"Copy check skipped for {source['full_name']}: {error}")
            continue

        identical = sum(1 for sha in mine if sha in theirs)
        if best is None or identical > best["identical"]:
            best = {"source": source["full_name"], "stars": source["stars"],
                    "identical": identical, "total": len(mine)}

    if best and best["identical"] >= MIN_IDENTICAL and best["identical"] / best["total"] >= MIN_SHARE:
        return best
    return None
